# ── 辅助 ───────────────────────────────────────────────

def fields_for(key: str) -> list:
    """某分类的全部字段 [(key, 中文标签), ...] (统一表头)。"""
    return list(COMMON_FIELDS)


def subcats(key: str) -> list:
    """某分类的子分类列表。"""
    return CATEGORIES[key][1]


def subcat_owners(subcat: str) -> list:
    """包含该子分类的所有一级分类 key (按 CATEGORIES 顺序)。

    同一个子分类可能出现在多个一级分类下 (元器件多属性, 便于查找),
    但物理 Excel 文件只建一份, 多个一级分类入口指向同一文件。
    """
    return [key for key, (_, subs) in CATEGORIES.items() if subcat in subs]


def primary_owner(subcat: str) -> str | None:
    """子分类物理文件所在的一级分类 key (取第一个归属)。"""
    owners = subcat_owners(subcat)
    return owners[0] if owners else None


def safe_filename(name: str) -> str:
    """Windows 文件名安全化: 替换 / \\ : * ? \" < > | 为 -。"""
    return re.sub(r'[\\/:*?"<>|]', "-", name)


def all_subcat_labels() -> list:
    """所有子分类并集 (AI 解析用)。"""
    labels = set()
    for key in CATEGORIES:
        labels.update(subcats(key))
    return sorted(labels)
